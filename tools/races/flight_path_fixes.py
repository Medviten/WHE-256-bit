#!/usr/bin/env python3
"""Drop bad points from flight paths, as TaxiPathNode SQL: DELETE the points, renumber the rest.

  python -I flight_path_fixes.py OUT_SQL [--dbc DIR] PATH[:I,I...] ...

For every PATH (a TaxiPath id): points that repeat the one before (zero-length legs, which Open Azeroth's flight
generator puts at the nodes) go, and so do the node indices after the colon. node_index is renumbered from 0, as
AzerothCore keeps a path's points in a vector by index and a gap leaves a hole. Row ids stay as they are."""
import argparse, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import cata406_dbc_port as c406  # noqa: E402
from transport_paths import DBC  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("paths", nargs="+")
    ap.add_argument("--dbc", default=DBC)
    a = ap.parse_args()
    points = {}
    for r in c406.Dbc(os.path.join(a.dbc, "TaxiPathNode.dbc")).records:
        points.setdefault(r[1], []).append(r)
    out = ["-- Generated by tools/races/flight_path_fixes.py %s: change the arguments, not this file." % " ".join(a.paths)]
    for spec in a.paths:
        pid, _, drops = spec.partition(":")
        pid, drop = int(pid), {int(i) for i in drops.split(",") if i}
        rows = sorted(points[pid], key=lambda r: r[2])
        keep, gone = [], []
        for r in rows:
            pos = tuple(c406.f32(v) for v in r[4:7])
            if r[2] in drop or (keep and r[3] == keep[-1][3] and math.dist(pos, tuple(
                    c406.f32(v) for v in keep[-1][4:7])) < 0.5):
                gone.append(r)
            else:
                keep.append(r)
        assert len(keep) >= 2, pid
        out.append("\n-- path %d: %d of %d points dropped (%s)" % (pid, len(gone), len(rows),
                                                                 ", ".join(str(r[2]) for r in gone)))
        out.append("DELETE FROM `taxipathnode` WHERE `id` IN (%s);" % ", ".join(str(r[0]) for r in gone))
        out += ["UPDATE `taxipathnode` SET `node_index` = %d WHERE `id` = %d;" % (i, r[0])
                for i, r in enumerate(keep) if r[2] != i]
        print("path %d: dropped %s" % (pid, [r[2] for r in gone]))
    open(a.out, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
