#!/usr/bin/env python3
"""Generate the Dracthyr modpaks (F-073 Alliance, race 52; F-074 Horde, race 70) with new_race_modpaks.py's templates
(F-045 Alliance, F-046 Horde) and Home/Kin scheme: Home and Kin Human for the Alliance, Orc for the Horde.

Dracthyr only look right in the wowdecomp-256-bit client, which shows races mapped by its retailRaces setting
(default "52=52,70=70") with their Retail model and customization. The DBC rows here are what everything else sees:
the Home race's stock model and customization rows (a client without Retail support shows a human or an orc), and the
row-0 CharSections lookups the Retail client points its stock selectors at.

usage: dracthyr_modpaks.py <built DBFilesClient> [modpaks dir] [output dir]
       (then tools/races/coa_racials.py adds CoA's Dracthyr racials)"""
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import new_race_modpaks as nrm   # noqa: E402

RACES = [
    ('AllianceDracthyr', 'Dracthyr', 'Dracthyr', 73, 'dracthyr-alliance', 'Alliance', 'Human', 'Human', False,
     ('stock', 49, 50), ('npc', 1), 'Hu',
     'Obsidian Warders', 'Dracthyr who joined the Alliance after waking on the Forbidden Reach.',
     'The dracthyr were made by Neltharion to be his perfect soldiers, then sealed away for millennia.'),
    ('HordeDracthyr', 'Dracthyr', 'Dracthyr', 74, 'dracthyr-horde', 'Horde', 'Orc', 'Orc', False,
     ('stock', 51, 52), ('npc', 2), 'Or',
     'Dark Talons', 'Dracthyr who joined the Horde after waking on the Forbidden Reach.',
     'The dracthyr were made by Neltharion to be his perfect soldiers, then sealed away for millennia.'),
]


def write_readme(out, key, name, plural, fnum, slug, side, home, kin, male_only, model, source, prefix):
    lines = ['# mod-worgoblin-high-elf', '## F-0%d_mod-playable-%s' % (fnum, slug), '', '### Features',
             '- Playable %s (%s), race ID %d (retail\'s) set in config.sql' % (plural, side, 52 if side == 'Alliance' else 70),
             '    - Retail model and full Retail customization in the wowdecomp-256-bit client (its `retailRaces` setting, '
             'default `52=52,70=70`), Dragon and Visage forms (Two Forms)',
             '    - Everything else sees the %s model and customization rows (a client without Retail support shows a '
             '%s)' % (home, home.lower()),
             '    - Home: %s (classes, start position, start outfits, action bars, stats, totems, druid forms, race-restricted'
             % home, '      quests and items)', '    - Kin: %s (voice, emotes and names, copied at build time)' % kin,
             '    - Helmet prefix \'%s\'' % prefix,
             '- Generated by `tools/races/dracthyr_modpaks.py` (tentative, for testing)', '',
             '### Requirements',
             '- wowdecomp-256-bit client built with `WOWDECOMP_RETAIL_ASSETS=ON`, with the Dracthyr Retail files '
             '(local CASC, a `pack=` folder or the Blizzard CDN)',
             '- azerothcore-wotlk-256-bit with the Retail look tables and opcodes (characters keep their full '
             'customization and both forms; `RetailLook.TwoFormsRaces`)',
             '- Interface: race button and the %s entries in `CharacterCreate.lua/.xml`, `GlueParent.lua` and '
             '`GlueStrings.lua`; `RetailRace_CharacterCreate.lua` for the Retail options' % key.upper(),
             '', '### Known Issues', '- Tentative: not tested in game yet', '- No racial mount',
             '- Placeholder race icon',
             '- No in-world form toggle yet (Visage): the form chosen in the character creator stays',
             '- Soar flies with the stock flight rules; no Skyriding',
             '- Model size and collision are the %s model\'s' % home]
    nrm.write(os.path.join(out, 'readme.md'), '\n'.join(lines))


def main():
    nrm.BUILT = nrm.DONOR = sys.argv[1]
    nrm.MODPAKS = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', '..', 'modpaks')
    nrm.OUTPUT = sys.argv[3] if len(sys.argv) > 3 else nrm.MODPAKS
    nrm.RACES = RACES
    nrm.write_readme = write_readme
    nrm.main()
    for race in RACES:
        fix_wording(os.path.join(nrm.OUTPUT, 'F-0%d_mod-playable-%s' % (race[3], race[4])), race[6], race[10][1])


def fix_wording(out, home, race):
    """The customization rows are the Home race's own, not NPC rows moved by F-008."""
    for name in ('charsections', 'charhairgeosets', 'characterfacialhairstyles'):
        for path in glob.glob(os.path.join(out, 'dbc', '*_%s.sql' % name)):
            text = open(path, encoding='utf-8').read()
            text = text.replace('the stock NPC race rows (race %d after F-008)' % race,
                                'the %s rows (race %d), which the Retail client only reads at row 0' % (home, race))
            nrm.write(path, text.replace(', flagged for character creation (17, faces 1)',
                                         ', with their flags (NPC-only and Death Knight skins stay so)'))


if __name__ == '__main__':
    main()
