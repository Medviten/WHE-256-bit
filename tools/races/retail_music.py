#!/usr/bin/env python3
"""Retail's music and ambience for a retail map port's areas (F-137 Exile's Reach): mop_map_port.py's write_music for
retail's tables, which name files by sound kit.

  python -I -X utf8 retail_music.py CSV_DIR MODPAK [--tags F-137,F-137,DC] [--listfile CSV]

CSV_DIR holds wago.tools' exports of the retail build (12.1.5.70961 for F-137): AreaTable, ZoneMusic, SoundAmbience,
ZoneIntroMusicTable, SoundKit, SoundKitEntry. For every area MODPAK's dbc/[TAG]_areatable.sql writes, its retail
AmbienceID, ZoneMusic and IntroSound become SoundAmbience, ZoneMusic and ZoneIntroMusicTable rows at retail's ids, and
the sound kits they play SoundEntries rows at the kit's id: the kit's files (SoundKitEntry, named through the
community listfile; those in the first file's folder, up to 10) with the kit's volume, flags and distances. Ids stock
has stay stock's rows (the same sounds), ids another modpak writes are left to it. Writes
MODPAK/dbc/[TAG]_music_*.sql (the first tag) and sets the areatable SQLs' ambience, zone_music and zone_music_intro.
Fetch the files into WHE-common afterwards: zep_goblin_sounds.py --sql MODPAK/dbc/[TAG]_music_soundentries.sql
--common <WHE-common>/patch-ER.MPQ --build <retail build>.
"""
import argparse, collections, csv, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from cata406_dbc_port import Dbc, block  # noqa: E402
from mop_map_port import taken_ids, apply_music, MUSIC_COLUMNS  # noqa: E402
from mop_wandering_isle_port import STOCK_DBC  # noqa: E402

HEADER = "-- Generated by tools/races/retail_music.py: change the script, not this file.\n\n"
LISTFILE = "D:/wow-scratch/listfile/community-listfile.csv"
# retail AreaTable column -> (3.3.5a table, its areatable column)
AREA_FIELDS = (("AmbienceID", "soundambience", "ambience"), ("ZoneMusic", "zonemusic", "zone_music"),
               ("IntroSound", "zoneintromusictable", "zone_music_intro"))


def table(csv_dir, name):
    csv.field_size_limit(1 << 24)
    with open(os.path.join(csv_dir, name + ".csv"), encoding="utf-8", newline="") as fh:
        return {int(r["ID"]): r for r in csv.DictReader(fh)}


def n(v):
    try:
        return int(float(v or 0))
    except ValueError:
        return 0


class Kits:
    """Retail sound kits as 3.3.5a SoundEntries rows."""

    def __init__(self, csv_dir, listfile, stock, taken):
        self.kits = table(csv_dir, "SoundKit")
        self.entries = collections.defaultdict(list)
        for r in table(csv_dir, "SoundKitEntry").values():
            self.entries[n(r["SoundKitID"])].append(r)
        self.listfile, self.paths = listfile, None
        self.stock, self.taken, self.out = stock, taken, {}

    def path(self, fid):
        if self.paths is None:
            want = {n(r["FileDataID"]) for rs in self.entries.values() for r in rs}
            self.paths = {}
            for line in open(self.listfile, encoding="utf-8", errors="replace"):
                f, _, p = line.strip().partition(";")
                if f.isdigit() and int(f) in want:
                    self.paths[int(f)] = p
        return self.paths.get(fid)

    def sound(self, kit):
        """The SoundEntries id playing the kit (its own), 0 when no file of it is named."""
        if kit <= 0:
            return 0
        if kit in self.out or self.stock.get(kit) or kit in self.taken:
            return kit
        k = self.kits.get(kit)
        rows = sorted(self.entries.get(kit, []), key=lambda r: n(r["ID"]))
        files = [(self.path(n(r["FileDataID"])), r) for r in rows]
        files = [(p, r) for p, r in files if p]
        if not k or not files:
            return 0
        base = files[0][0].rsplit("/", 1)[0]
        files = [(p, r) for p, r in files if p.rsplit("/", 1)[0] == base][:10]
        name = os.path.splitext(files[0][0].rsplit("/", 1)[1])[0]
        c = {"id": kit, "sound_type": n(k["SoundType"]), "name": name}
        for i, (p, r) in enumerate(files):
            c["file_%d" % (i + 1)] = p.rsplit("/", 1)[1]
            c["frequency_%d" % (i + 1)] = max(1, n(r["Frequency"]))
        c.update(base_dir=base.replace("/", "\\"), volume=round(float(k["VolumeFloat"] or 1), 4),
                 flags=n(k["Flags"]), min_distance=round(float(k["MinDistance"] or 0), 4),
                 distance_cutoff=round(float(k["DistanceCutoff"] or 0), 4),
                 eax_def=n(k["EAXDef"]), advanced_id=0)
        self.out[kit] = c
        return kit


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("csv_dir")
    p.add_argument("modpak")
    p.add_argument("--tags", default="F-137,F-137,DC", help="the areatable files' tags; the first names the output")
    p.add_argument("--listfile", default=LISTFILE)
    a = p.parse_args()
    tags = ["F-137", "F-137,DC"] if a.tags == "F-137,F-137,DC" else a.tags.split(";")
    tag, dbc_dir = "[%s]" % tags[0], os.path.join(a.modpak, "dbc")
    modpaks_dir = os.path.dirname(os.path.abspath(a.modpak))
    files = [os.path.join(dbc_dir, "[%s]_areatable.sql" % t) for t in tags]
    areas = sorted({int(x) for f in files for x in re.findall(r"INSERT INTO `areatable` SET\s*`id` = (\d+)",
                                                            open(f, encoding="utf-8").read())})
    retail = {"areatable": table(a.csv_dir, "AreaTable"), "soundambience": table(a.csv_dir, "SoundAmbience"),
              "zonemusic": table(a.csv_dir, "ZoneMusic"),
              "zoneintromusictable": table(a.csv_dir, "ZoneIntroMusicTable")}
    stock = {t: Dbc(os.path.join(STOCK_DBC, d + ".dbc")) for t, d in
             (("soundambience", "SoundAmbience"), ("zonemusic", "ZoneMusic"),
              ("zoneintromusictable", "ZoneIntroMusicTable"), ("soundentries", "SoundEntries"))}
    taken = {t: taken_ids(modpaks_dir, t, tag) for t in stock}
    kits = Kits(a.csv_dir, a.listfile, stock["soundentries"], taken["soundentries"])
    music, rows = collections.defaultdict(dict), collections.defaultdict(dict)
    for area in areas:
        r = retail["areatable"].get(area)
        for field, t, column in AREA_FIELDS:
            mid = n(r and r[field])
            src = retail[t].get(mid)
            if not src:
                continue
            if mid in rows[t]:
                if rows[t][mid] is not None:
                    music[area][column] = mid
                continue
            if stock[t].get(mid) or mid in taken[t]:
                rows[t][mid] = {}                       # stock's or another modpak's row
                music[area][column] = mid
                continue
            if t == "soundambience":
                cols = dict(zip(MUSIC_COLUMNS[t], (mid, kits.sound(n(src["AmbienceID_0"])),
                                                    kits.sound(n(src["AmbienceID_1"])))))
                ok = cols["sound_entry_id_day"] or cols["sound_entry_id_night"]
            elif t == "zonemusic":
                cols = dict(zip(MUSIC_COLUMNS[t], (mid, src["SetName"], n(src["SilenceIntervalMin_0"]),
                                                    n(src["SilenceIntervalMin_1"]), n(src["SilenceIntervalMax_0"]),
                                                    n(src["SilenceIntervalMax_1"]), kits.sound(n(src["Sounds_0"])),
                                                    kits.sound(n(src["Sounds_1"])))))
                ok = cols["day_music"] or cols["night_music"]
            else:
                cols = dict(zip(MUSIC_COLUMNS[t], (mid, src["Name"], kits.sound(n(src["SoundID"])), n(src["Priority"]),
                                                    n(src["MinDelayMinutes"]))))
                ok = cols["sound_id"]
            rows[t][mid] = cols if ok else None
            if ok:
                music[area][column] = mid
    for t in ("soundambience", "zonemusic", "zoneintromusictable"):
        out = [block(t, k, c, "%s (retail's)" % c.get("name", k)) for k, c in sorted(rows[t].items()) if c]
        with open(os.path.join(dbc_dir, "%s_music_%s.sql" % (tag, t)), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(HEADER + "\n".join(out))
    with open(os.path.join(dbc_dir, "%s_music_soundentries.sql" % tag), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER + "-- The files the areas' music and ambience play (retail's sound kits)\n\n" + "\n".join(
            block("soundentries", k, c, "%d %s" % (k, c["name"])) for k, c in sorted(kits.out.items())))
    for f in files:
        apply_music(f, music)
    print("music for %d of %d areas, %d sound entries" % (len(music), len(areas), len(kits.out)))


if __name__ == "__main__":
    main()
