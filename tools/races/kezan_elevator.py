#!/usr/bin/env python3
"""The goblin elevator of Kezan's zeppelin tower (F-142), from Cataclysm's own goblin elevator.

  python -I kezan_elevator.py CATA_DBC_DIR MODPAK_DIR

Cataclysm used gameobject 204246 (Doodad_Goblin_elevator01, display 9693, goblin_elevator.m2, which Open Azeroth's maps
ship) in Azshara's goblin towers; Open Azeroth's Kezan tower (goblin_freewaytower.wmo, at (-8927.7, -10654.5, 113.5))
has the shaft but no car. Writes MODPAK_DIR/dbc/[F-142]_goblin_elevator.sql (the display, from 4.0.6a's
GameObjectDisplayInfo, and the car's TransportAnimation: 204246's timing, its 38.75-yard rise stretched to the shaft's
height) and MODPAK_DIR/sql/db-world/base/[F-142]_kezan_elevator.sql (the object and its spawn at the bottom of the shaft).
The shaft's ends are .gps readings in game: the car's floor rests on them."""
import math, os, struct, sys

ENTRY, GUID, DISPLAY, SOURCE = 1420001, 14200001, 9693, 204246
BOTTOM = (-8927.875, -10672.941, 113.70)          # .gps standing at the foot of the shaft
TOP_Z = 153.12                                    # .gps on the landing at its top
FACING = math.radians(-2.0 + 180.0 - 90.0)        # the tower's (MODF yaw -2, world yaw = MODF + 180, CMap::CreateMapObjDef),
                                                  # turned 90 degrees right so the car's open sides face the landings (seen in game)


def rows(path):
    d = open(path, 'rb').read()
    _, n, f, size, _ = struct.unpack('<4s4i', d[:20])
    return [d[20 + i * size:20 + (i + 1) * size] for i in range(n)], d[20 + n * size:]


def main():
    cata, out = sys.argv[1], sys.argv[2]
    gdi, strs = rows(os.path.join(cata, 'GameObjectDisplayInfo.dbc'))
    disp = next(r for r in gdi if struct.unpack_from('<I', r)[0] == DISPLAY)
    off = struct.unpack_from('<I', disp, 4)[0]
    model = strs[off:strs.index(b'\0', off)].decode('latin1')
    box = struct.unpack_from('<6f', disp, 48)
    anim, _ = rows(os.path.join(cata, 'TransportAnimation.dbc'))
    frames = sorted((struct.unpack_from('<I', r, 8)[0], struct.unpack_from('<3f', r, 12)) for r in anim
                    if struct.unpack_from('<I', r, 4)[0] == SOURCE)
    rise = max(p[2] for _, p in frames)
    scale = (TOP_Z - BOTTOM[2]) / rise
    assert 0.9 < scale < 1.1, scale

    dbc = ["-- [F-142] Kezan's goblin elevator: display %d and the car's animation. Generated by" % DISPLAY,
           "-- tools/races/kezan_elevator.py from Cataclysm 4.0.6a's DBCs (gameobject %d's animation, its %.2f-yard rise"
           % (SOURCE, rise), "-- stretched to the shaft's %.2f): change the script, not this file." % (TOP_Z - BOTTOM[2]), "",
           "DELETE FROM `gameobjectdisplayinfo` WHERE `id` = %d;" % DISPLAY,
           "INSERT INTO `gameobjectdisplayinfo` (`id`, `model_name`, %s, `geo_box_min_x`, `geo_box_min_y`, `geo_box_min_z`, "
           "`geo_box_max_x`, `geo_box_max_y`, `geo_box_max_z`) VALUES" % ", ".join("`sound_%d`" % i for i in range(1, 11)),
           "  (%d, '%s', %s, %s);" % (DISPLAY, model.replace('\\', '\\\\'), ", ".join(["0"] * 10),
                                       ", ".join("%.4f" % v for v in box)), "",
           "DELETE FROM `transportanimation` WHERE `transport_id` = %d;" % ENTRY,
           "SET @TransportAnimationID = (SELECT COALESCE(MAX(`id`), 0) FROM `transportanimation`);",
           "INSERT INTO `transportanimation` (`id`, `transport_id`, `time_index`, `x`, `y`, `z`, `sequence_id`) VALUES"]
    dbc.append(",\n".join("  (@TransportAnimationID := @TransportAnimationID + 1, %d, %d, 0, 0, %.4f, 0)"
                          % (ENTRY, t, p[2] * scale) for t, p in frames) + ";")
    x, y, z = BOTTOM
    world = ["-- [F-142] Kezan's goblin elevator, in the shaft of the zeppelin tower. Generated by",
             "-- tools/races/kezan_elevator.py: change the script, not this file.", "",
             "DELETE FROM `gameobject_template` WHERE `entry` = %d;" % ENTRY,
             "INSERT INTO `gameobject_template` (`entry`, `type`, `displayId`, `name`, `IconName`, `castBarCaption`, "
             "`unk1`, `size`, %s, `AIName`, `ScriptName`, `VerifiedBuild`) VALUES" % ", ".join("`Data%d`" % i for i in range(24)),
             "  (%d, 11, %d, 'Goblin Elevator', '', '', '', 1, %s, '', '', 0);" % (ENTRY, DISPLAY, ", ".join(["0"] * 24)), "",
             "DELETE FROM `gameobject_template_addon` WHERE `entry` = %d;" % ENTRY,
             "INSERT INTO `gameobject_template_addon` (`entry`, `faction`, `flags`) VALUES (%d, 0, 40);" % ENTRY, "",
             "DELETE FROM `gameobject` WHERE `guid` = %d;" % GUID,
             "INSERT INTO `gameobject` (`guid`, `id`, `map`, `zoneId`, `areaId`, `spawnMask`, `phaseMask`, `position_x`, "
             "`position_y`, `position_z`, `orientation`, `rotation0`, `rotation1`, `rotation2`, `rotation3`, "
             "`spawntimesecs`, `animprogress`, `state`) VALUES",
             "  (%d, %d, 1, 0, 0, 1, 1, %.3f, %.3f, %.3f, %.5f, 0, 0, %.7f, %.7f, 180, 0, 1);"
             % (GUID, ENTRY, x, y, z, FACING, math.sin(FACING / 2), math.cos(FACING / 2))]
    for sub, name, text in (('dbc', '[F-142]_goblin_elevator.sql', dbc),
                            (os.path.join('sql', 'db-world', 'base'), '[F-142]_kezan_elevator.sql', world)):
        os.makedirs(os.path.join(out, sub), exist_ok=True)
        open(os.path.join(out, sub, name), 'w', encoding='utf-8', newline='\n').write('\n'.join(text) + '\n')
    print('display %d %s; %d frames, rise %.2f -> %.2f' % (DISPLAY, model, len(frames), rise, rise * scale))


if __name__ == '__main__':
    main()
