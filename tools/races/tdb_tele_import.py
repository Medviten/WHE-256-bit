#!/usr/bin/env python3
"""`.tele` targets from TrinityCore's Cataclysm world database, for Open Azeroth's Kalimdor and Eastern Kingdoms.

  python -I tdb_tele_import.py TDB_SQL MODPAK_DIR

TDB_SQL is a TDB 4.3.4 full world dump (References\\Cataclysm\\Cataclysm_DB). Open Azeroth's terrain is converted
from Cataclysm's, so TDB's hand-placed targets on maps 0 and 1 fit it. Takes the ones whose names stock's game_tele
(azerothcore-wotlk-256-bit) doesn't have, and those whose names tools/races/oa_area_tele.py generated (TDB's spot is
picked by hand, the generated one is only a dry chunk near the area's middle). Leaves out names the modpak's
hand-picked zz_[F-010]_game_tele.sql sets, and other maps (Tol Barad is map 732 in TDB but part of the Eastern
Kingdoms here).

Writes MODPAK_DIR/sql/db-world/base/zz_[F-010]_game_tele_cata.sql, ids from ID_BASE. It sorts after
zz_[F-010]_game_tele_areas.sql and deletes by name first, so its targets replace the generated ones."""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
STOCK_TELE = os.path.join(HERE, "..", "..", "..", "azerothcore-wotlk-256-bit", "data", "sql", "base", "db_world",
                          "game_tele.sql")
ID_BASE = 89000
MAPS = (0, 1)
ROW = re.compile(r"\((\d+),\s*(-?[\d.e+-]+),\s*(-?[\d.e+-]+),\s*(-?[\d.e+-]+),\s*(-?[\d.e+-]+),\s*(\d+),\s*"
                 r"'((?:[^'\\]|\\.|'')*)'\)")


def teles(text):
    return {m.group(7).replace("\\'", "'").replace("''", "'"): tuple(float(v) for v in m.group(2, 3, 4, 5))
            + (int(m.group(6)),) for m in ROW.finditer(text)}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    tdb_text = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    i = tdb_text.index("INSERT INTO `game_tele` VALUES")
    tdb = teles(tdb_text[i:tdb_text.index(";\n", i)])
    base = os.path.join(sys.argv[2], "sql", "db-world", "base")
    stock = {n.lower() for n in teles(open(STOCK_TELE, encoding="utf-8").read())}
    hand = {n.lower() for n in teles(open(os.path.join(base, "zz_[F-010]_game_tele.sql"), encoding="utf-8").read())}
    gen = {n.lower() for n in teles(open(os.path.join(base, "zz_[F-010]_game_tele_areas.sql"),
                                         encoding="utf-8").read())}
    new, better = [], []
    for name, (x, y, z, o, m) in sorted(tdb.items(), key=lambda kv: kv[0].lower()):
        key = name.lower()
        if m not in MAPS or key in hand:
            continue
        if key in gen:
            better.append((name, x, y, z, o, m))
        elif key not in stock:
            new.append((name, x, y, z, o, m))
    rows = new + better
    q = lambda n: n.replace("'", "''")
    text = ["-- .tele targets from TrinityCore's Cataclysm world database (TDB 4.3.4), whose terrain Open Azeroth's is",
            "-- converted from: %d it has and stock doesn't, and %d that replace tools/races/oa_area_tele.py's generated"
            % (len(new), len(better)),
            "-- spots with TDB's hand-placed ones. Generated by tools/races/tdb_tele_import.py: change the script, not",
            "-- this file.",
            "DELETE FROM `game_tele` WHERE `id` BETWEEN %d AND %d;" % (ID_BASE, ID_BASE + 999),
            "DELETE FROM `game_tele` WHERE `name` IN (%s);" % ", ".join("'%s'" % q(r[0]) for r in rows),
            "INSERT INTO `game_tele` (`id`, `position_x`, `position_y`, `position_z`, `orientation`, `map`, `name`) "
            "VALUES",
            ",\n".join("(%d, %.4f, %.4f, %.4f, %.4f, %d, '%s')" % (ID_BASE + i, x, y, z, o, m, q(n))
                       for i, (n, x, y, z, o, m) in enumerate(rows)) + ";"]
    assert len(rows) < 1000
    out = os.path.join(base, "zz_[F-010]_game_tele_cata.sql")
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(text) + "\n")
    print("%d new, %d replacing generated ones: %s" % (len(new), len(better), out))
    print("new:", ", ".join(r[0] for r in new))
    print("replacing:", ", ".join(r[0] for r in better))


if __name__ == "__main__":
    main()
