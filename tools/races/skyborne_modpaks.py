#!/usr/bin/env python3
"""Generate the Skyborne modpaks (F-103 Alliance, race 95; F-104 Horde, race 96) with new_race_modpaks.py's templates,
like haranir_modpaks.py: Home Human and Kin Blood Elf for the Alliance (as Void Elf and High Elf), Blood Elf for both
on the Horde. Helmets and model size are the Blood Elf's: the Skyborne bodies are Blood Elf rigs.

The wowdecomp-256-bit client draws races its retailRaces setting maps with "race=forever:<id>" (default
"95=forever:95,96=forever:96") with the Forever model and customization, when a Forever configuration is installed
(Data/Retail/ForeverCasc.ini). Everything else sees the native model with baked textures from Kalibro's races package
(tools/races/skyborne_native.py writes their rows here and copies the files to WHE-common; tools/models/
skyborne_native_prep.py, which it runs, fixes the models' geosets), and the Forever client points its stock selectors at row 0 of those
rows. There are no racials.

usage: skyborne_modpaks.py <built DBFilesClient> [modpaks dir] [output dir] [--package PATH] [--common PATH]
       then, with `report` first: tools/racemask/word2vars.py and word2.py <modpaks dir> apply"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import new_race_modpaks as nrm   # noqa: E402
import skyborne_native   # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
LORE = 'Skyborne high elves of Zephras Isle, raised to Skywall by their pact with the wind spirits, who fight beside the %s.'
RACES = [
    ('AllianceSkyborne', 'Skyborne', 'Skyborne', 103, 'skyborne-alliance', 'Alliance', 'Human', 'BloodElf', False,
     ('stock', 2208, 2209), ('npc', 10), 'Be', 'High Order of Zephras', LORE % 'Alliance', ''),
    ('HordeSkyborne', 'Skyborne', 'Skyborne', 104, 'skyborne-horde', 'Horde', 'BloodElf', 'BloodElf', False,
     ('stock', 2208, 2209), ('npc', 10), 'Be', 'Windshapers of Zephras', LORE % 'Horde', ''),
]
LABEL = {'Human': 'Human', 'BloodElf': 'Blood Elf'}
BLOOD_ELF_DISPLAYS = (15476, 15475)


def folder_name(fnum, slug):
    return 'F-%03d_mod-%s' % (fnum, slug)


def write_readme(out, key, name, plural, fnum, slug, side, home, kin, male_only, model, source, prefix):
    native = skyborne_native.SUMMARY
    lines = ['# mod-worgoblin-high-elf', '## ' + folder_name(fnum, slug), '', '### Features',
             "- Playable %s (%s), race ID %d (Forever's) set in config.sql" % (plural, side, 95 if side == 'Alliance' else 96),
             '    - Forever model and full Forever customization in the wowdecomp-256-bit client (its `retailRaces` setting, '
             'default `...,95=forever:95,96=forever:96`), when `Data/Retail/ForeverCasc.ini` is installed',
             "    - Any other client (and the Retail client without Forever data) shows the native model from Kalibro's races "
             'package: ' + native,
             '    - Home: %s (classes, start position, start outfits, action bars, stats, totems, druid forms, race-restricted'
             % LABEL[home], '      quests and items)',
             '    - Kin: %s (voice, emotes and names, copied at build time)' % LABEL[kin],
             "    - Helmet prefix '%s'" % prefix,
             '- Generated by `tools/races/skyborne_modpaks.py` (tentative, for testing)', '',
             '### Requirements',
             '- The client assets in WHE-common (`custom/skyborne`)',
             '- For the Forever look: wowdecomp-256-bit client built with `WOWDECOMP_RETAIL_ASSETS=ON`, with '
             '`config/ForeverCasc.example.ini` copied to `Data/Retail/ForeverCasc.ini` and the Skyborne Forever files '
             '(`RetailPackBuild --forever Data/Retail/ForeverPack 95 96`, or the Blizzard CDN)',
             '- azerothcore-wotlk-256-bit with the Retail look tables and opcodes (characters keep their full customization)',
             '- Interface: race button and the %s entries in `CharacterCreate.lua/.xml`, `GlueParent.lua` and '
             '`GlueStrings.lua`; `RetailRace_CharacterCreate.lua` for the Forever options' % key.upper(),
             '', '### Known Issues', '- Tentative: not tested in game yet', '- No racial abilities yet', '- No racial mount',
             '- No Skyborne voice: Blood Elf sounds', '- Placeholder racial faction name and description',
             '- Native look: ' + skyborne_native.LIMITS,
             '- Race ID above 64: `HelmetGeosetVisData` has no rows for it in a client without Retail support, so hair is '
             'not hidden under helmets there']
    nrm.write(os.path.join(out, 'readme.md'), '\n'.join(lines))


def fix_generated(key, fnum, slug, home, kin):
    out = os.path.join(nrm.OUTPUT, folder_name(fnum, slug))
    tag = '[BASE,F-%03d]' % fnum
    # The template's CoA racial (Slime Giant's Gooey Slam) isn't for this race
    for table in ('spell', 'skilllineability'):
        os.remove(os.path.join(out, 'dbc', '%s_%s.sql' % (tag, table)))
    # Home and Kin: the template's own rows aren't turned into variables by from_template
    nrm.write(os.path.join(out, 'sql', 'db-world', 'base', '%s_player_race_template.sql' % tag),
              "/* The stock races this race copies, see F-091_race-setup */\n"
              "DELETE FROM `player_race_template` WHERE `race` = @%s;\n"
              "INSERT INTO `player_race_template` (`race`, `home_race`, `kin_race`, `shapeshift_skin_color`) VALUES\n"
              "(@%s, @%s, @%s, 0);" % (key, key, home, kin))
    # Bounding radius and combat reach of the Blood Elf displays, whatever the Home race (the model is a Blood Elf rig)
    name = os.path.join(out, 'sql', 'db-world', 'base', '%s_creature_model_info.sql' % tag)
    text = open(name, encoding='utf-8').read()
    home_displays = nrm.HOME_DISPLAYS[home]
    for old, new in zip(home_displays, BLOOD_ELF_DISPLAYS):
        text = text.replace('`DisplayID` = %d' % old, '`DisplayID` = %d' % new)
    nrm.write(name, text.replace('of the %s displays' % home, 'of the BloodElf displays'))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('built')
    ap.add_argument('modpaks', nargs='?', default=os.path.join(HERE, '..', '..', 'modpaks'))
    ap.add_argument('output', nargs='?')
    ap.add_argument('--package', default=skyborne_native.PACKAGE)
    ap.add_argument('--common', default=skyborne_native.COMMON)
    a = ap.parse_args()
    nrm.BUILT = nrm.DONOR = a.built
    nrm.MODPAKS = a.modpaks
    nrm.OUTPUT = a.output or a.modpaks
    nrm.RACES = RACES
    nrm.write_readme = write_readme
    nrm.folder_name = folder_name
    nrm.main()
    for race in RACES:
        fix_generated(race[0], race[3], race[4], race[6], race[7])
    skyborne_native.apply(nrm.OUTPUT, a.package, a.common)


if __name__ == '__main__':
    main()
