#!/usr/bin/env python3
"""Spawn a map's gathering nodes (herbs, ore) from a TrinityCore full world dump as an AzerothCore modpak SQL file.

  python -I tdb_gathering_nodes.py TDB_WORLD_SQL OUT_SQL --map 860 --entries 1731,1617,1618,1619
                                  [--guid-base 13409000] [--comment "F-134 gathering node"]

TDB_WORLD_SQL is TrinityCore's TDB_full_world_*.sql (retail; https://github.com/TrinityCore/TrinityCore/releases).
Every `gameobject` spawn on --map whose entry is in --entries becomes a 3.3.5a spawn (phase mask 1, spawn mask 1)
with TrinityCore's position, rotation and respawn time. The entries must exist in AzerothCore already: retail's
low-level nodes (Copper Vein 1731, Peacebloom 1618, Silverleaf 1617, Earthroot 1619) keep their WotLK ids, as
type 3 (chest) objects with the gathering lock in AC instead of retail's type 50.

F-134 (the Wandering Isle, whose TC MoP Classic quest data has no nodes): 138 spawns, 62 Copper Vein, 29 Silverleaf,
28 Earthroot, 19 Peacebloom."""
import argparse, re


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("tdb")
    p.add_argument("out")
    p.add_argument("--map", type=int, required=True)
    p.add_argument("--entries", required=True)
    p.add_argument("--guid-base", type=int, default=13409000)
    p.add_argument("--comment", default="gathering node (TrinityCore TDB)")
    a = p.parse_args()
    wanted = {int(e) for e in a.entries.split(",")}
    cols, cur, rows = {}, None, []
    for line in open(a.tdb, encoding="utf8", errors="replace"):
        m = re.match(r"CREATE TABLE `(\w+)`", line)
        if m:
            cur = m.group(1)
            cols[cur] = []
            continue
        if cur and line.startswith("  `"):
            cols[cur].append(line.split("`")[1])
        elif cur and line.startswith(")"):
            cur = None
        if line.startswith("INSERT INTO `gameobject` VALUES"):
            body = line[len("INSERT INTO `gameobject` VALUES"):].strip().rstrip(";")
            for tup in re.findall(r"\(([^()]*)\)", body):
                vals = [v.strip().strip("'") for v in re.split(r",(?=(?:[^']*'[^']*')*[^']*$)", tup)]
                r = dict(zip(cols["gameobject"], vals))
                if int(r["map"]) == a.map and int(r["id"]) in wanted:
                    rows.append(r)
    rows.sort(key=lambda r: int(r["guid"]))
    last = a.guid_base + len(rows) - 1
    out = ["-- Generated by tools/races/tdb_gathering_nodes.py from %s: change the script, not this file." % a.tdb.replace("\\", "/").split("/")[-1],
           "", "DELETE FROM `gameobject` WHERE `guid` BETWEEN %d AND %d;" % (a.guid_base, last),
           "INSERT INTO `gameobject` (`guid`, `id`, `map`, `zoneId`, `areaId`, `spawnMask`, `phaseMask`, `position_x`, "
           "`position_y`, `position_z`, `orientation`, `rotation0`, `rotation1`, `rotation2`, `rotation3`, "
           "`spawntimesecs`, `animprogress`, `state`, `ScriptName`, `VerifiedBuild`, `Comment`) VALUES"]
    out.append(",\n".join(
        "  (%d, %s, %d, 0, 0, 1, 1, %s, %s, %s, %s, %s, %s, %s, %s, %s, 255, 1, '', 0, '%s')" % (
            a.guid_base + i, r["id"], a.map, r["position_x"], r["position_y"], r["position_z"], r["orientation"],
            r["rotation0"], r["rotation1"], r["rotation2"], r["rotation3"], r["spawntimesecs"],
            a.comment.replace("'", "''")) for i, r in enumerate(rows)) + ";")
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    counts = {}
    for r in rows:
        counts[r["id"]] = counts.get(r["id"], 0) + 1
    print("%d spawns (guids %d-%d): %s" % (len(rows), a.guid_base, last, counts))


if __name__ == "__main__":
    main()
