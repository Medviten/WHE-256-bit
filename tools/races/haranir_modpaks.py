#!/usr/bin/env python3
"""Generate the Haranir modpaks (F-098 Alliance, race 86; F-099 Horde, race 91) with new_race_modpaks.py's templates,
like dracthyr_modpaks.py: Home Night Elf for the Alliance, Troll for the Horde (Kalibro's choices). Kin and helmets are
Night Elf on both sides: it is one model, and the client's RacePolicy.h already uses Night Elf helmet masks for it.

Haranir only look right in the wowdecomp-256-bit client, which shows races mapped by its retailRaces setting with their
Retail model and customization. The DBC rows here are what everything else sees: the Home race's stock model and
customization rows (a client without Retail support shows a night elf or a troll), and the row-0 CharSections lookups
the Retail client points its stock selectors at. There are no racials: CoA and Aetheria have none to take.

usage: haranir_modpaks.py <built DBFilesClient> [modpaks dir] [output dir]
       then, with `report` first: tools/racemask/word2.py <modpaks dir> apply"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dracthyr_modpaks as dracthyr   # noqa: E402
import new_race_modpaks as nrm   # noqa: E402

DESCRIPTION = "Haranir of Harandar who left the roots of the Goddess's domain to fight beside the %s."
RACES = [
    ('AllianceHaranir', 'Haranir', 'Haranir', 98, 'haranir-alliance', 'Alliance', 'NightElf', 'NightElf', False,
     ('stock', 55, 56), ('npc', 4), 'Ni', "Hara'ti Wardens", DESCRIPTION % 'Alliance', ''),
    ('HordeHaranir', 'Haranir', 'Haranir', 99, 'haranir-horde', 'Horde', 'Troll', 'NightElf', False,
     ('stock', 185, 186), ('npc', 8), 'Ni', "Hara'ti Hunters", DESCRIPTION % 'Horde', ''),
]
LABEL = {'NightElf': 'Night Elf', 'Troll': 'Troll'}


def write_readme(out, key, name, plural, fnum, slug, side, home, kin, male_only, model, source, prefix):
    lines = ['# mod-worgoblin-high-elf', '## F-0%d_mod-playable-%s' % (fnum, slug), '', '### Features',
             "- Playable %s (%s), race ID %d (retail's) set in config.sql" % (plural, side, 86 if side == 'Alliance' else 91),
             '    - Retail model and full Retail customization in the wowdecomp-256-bit client (its `retailRaces` setting, '
             'default `37=37,52=52,70=70,86=86,91=91`)',
             '    - Everything else sees the %s model and customization rows (a client without Retail support shows a %s)'
             % (LABEL[home], LABEL[home].lower()),
             '    - Home: %s (classes, start position, start outfits, action bars, stats, totems, druid forms, race-restricted'
             % LABEL[home], '      quests and items)',
             '    - Kin: %s (voice, emotes and names, copied at build time)' % LABEL[kin],
             "    - Helmet prefix '%s'" % prefix,
             '- Generated by `tools/races/haranir_modpaks.py` (tentative, for testing)', '',
             '### Requirements',
             '- wowdecomp-256-bit client built with `WOWDECOMP_RETAIL_ASSETS=ON`, with the Haranir Retail files '
             '(a `pack=` folder from `RetailPackBuild <pack> 86 91`, a local CASC or the Blizzard CDN)',
             '- azerothcore-wotlk-256-bit with the Retail look tables and opcodes (characters keep their full customization)',
             '- Interface: race button and the %s entries in `CharacterCreate.lua/.xml`, `GlueParent.lua` and '
             '`GlueStrings.lua`; `RetailRace_CharacterCreate.lua` for the Retail options' % key.upper(),
             '', '### Known Issues', '- Tentative: not tested in game yet', '- No racial abilities yet', '- No racial mount',
             '- No Haranir voice: Night Elf sounds', '- Placeholder racial faction name and description',
             "- Model size and collision are the %s model's" % LABEL[home],
             '- Race ID above 64: `HelmetGeosetVisData` has no rows for it in a client without Retail support, so hair is '
             'not hidden under helmets there']
    nrm.write(os.path.join(out, 'readme.md'), '\n'.join(lines))


def fix_generated(key, fnum, slug, home, kin):
    out = os.path.join(nrm.OUTPUT, 'F-0%d_mod-playable-%s' % (fnum, slug))
    # The template's CoA racial (Slime Giant's Gooey Slam) isn't for this race
    for table in ('spell', 'skilllineability'):
        os.remove(os.path.join(out, 'dbc', '[BASE,F-0%d]_%s.sql' % (fnum, table)))
    # Home and Kin: the template's own rows aren't turned into variables by from_template
    nrm.write(os.path.join(out, 'sql', 'db-world', 'base', '[BASE,F-0%d]_player_race_template.sql' % fnum),
              "/* The stock races this race copies, see F-091_race-setup */\n"
              "DELETE FROM `player_race_template` WHERE `race` = @%s;\n"
              "INSERT INTO `player_race_template` (`race`, `home_race`, `kin_race`, `shapeshift_skin_color`) VALUES\n"
              "(@%s, @%s, @%s, 0);" % (key, key, home, kin))
    dracthyr.fix_wording(out, LABEL[home], 4 if home == 'NightElf' else 8)


def main():
    nrm.BUILT = nrm.DONOR = sys.argv[1]
    nrm.MODPAKS = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'modpaks')
    nrm.OUTPUT = sys.argv[3] if len(sys.argv) > 3 else nrm.MODPAKS
    nrm.RACES = RACES
    nrm.write_readme = write_readme
    nrm.main()
    for race in RACES:
        fix_generated(race[0], race[3], race[4], race[6], race[7])


if __name__ == '__main__':
    main()
