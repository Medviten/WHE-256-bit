#!/usr/bin/env python3
"""Build the Questie-X-WHE addon: the world maps and area names a WHE realm adds or moves, for Questie-X.

  python questie_whe.py STOCK_DBC_DIR OUT_DIR --realm NAME=DBC_DIR [--realm NAME=DBC_DIR ...]

STOCK_DBC_DIR: stock 3.3.5a DBCs (References/original-client-dbc), what Questie-X's own map data matches.
DBC_DIR: a realm's built client DBCs (the client's Data/patch-A.<realm>.MPQ/DBFilesClient after deploy-dbc.sh).
NAME: the realm name as GetRealmName() returns it ("War", "256-bit"); the addon picks the matching set, or the first.
OUT_DIR: the addon folder, e.g. <client>/Interface/AddOns/Questie-X-WHE (Questie-X-WHE.toc, Data.lua, Plugin.lua).

Per realm, from WorldMapArea (only maps on open-world continents, whole-zone maps without dungeon floors, with bounds):
- moved: stock rows moved to another map (OA's Azuremyst, Eversong, ...), keyed by GetCurrentMapAreaID() (id + 1):
  {width, height, left, top, map}
- zones: rows stock lacks: the same plus {area id, name, map type (2 continent, 3 zone)}; stock rows that kept their
  map but changed bounds too, with a 9th value, true: for the player's position only
- areas: AreaTable rows stock lacks: {map, name}
Plugin.lua (next to this script) applies them; see its header. Rerun after the realm's DBCs change."""
import argparse, os, shutil, struct, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "races"))
from cata406_dbc_port import Dbc  # noqa: E402

TOC = """## Interface: 30300
## Title: |cFF5EBAF3Questie|r|cFFDAFAFD-X|r |cFF00FF00WHE maps|r
## Notes: The server's added and moved zones for Questie-X (generated by WHE's tools/questie/questie_whe.py)
## Dependencies: Questie-X
## OptionalDeps: Questie-X-WotLKDB

Data.lua
Plugin.lua
"""


def f(v):
    return struct.unpack("<f", struct.pack("<i", v))[0]


def num(x):
    return f"{x:.4f}".rstrip("0").rstrip(".")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def bounds(r):
    left, right, top, bottom = (f(v) for v in r[4:8])
    return [left - right, top - bottom, left, top]


def realm_data(stock_dir, dbc_dir):
    st_wma, wma = Dbc(os.path.join(stock_dir, "WorldMapArea.dbc")), Dbc(os.path.join(dbc_dir, "WorldMapArea.dbc"))
    maps = Dbc(os.path.join(dbc_dir, "Map.dbc"))
    st_area, area = Dbc(os.path.join(stock_dir, "AreaTable.dbc")), Dbc(os.path.join(dbc_dir, "AreaTable.dbc"))
    moved, zones = {}, {}
    for i, r in sorted(wma.rows.items()):
        m = maps.get(r[1])
        b = bounds(r)
        if not m or m[2] != 0 or r[9] or b[0] <= 0 or b[1] <= 0:
            continue
        s = st_wma.get(i)
        if s is None:
            name = area.s(area.get(r[2])[11]) if r[2] and area.get(r[2]) else maps.s(m[5])
            zones[i + 1] = b + [r[1], r[2], name, 3 if r[2] else 2]
        elif s[1] != r[1]:
            moved[i + 1] = b + [r[1]]
        elif bounds(s) != b:
            # Same terrain, new bounds (Blasted Lands' Cataclysm south): Questie's spawn coordinates stay relative to
            # the stock bounds, so only the player's position uses the new ones
            zones[i + 1] = b + [r[1], r[2], area.s(area.get(r[2])[11]), 3, 1]
    areas = {i: (r[1], area.s(r[11])) for i, r in sorted(area.rows.items()) if i not in st_area.rows}
    return moved, zones, areas


def emit(name, moved, zones, areas):
    out = [f"QuestieWHE_Data[{lua_str(name)}] = {{", "    moved = {"]
    for k, v in moved.items():
        out.append(f"        [{k}] = {{{', '.join(num(x) for x in v[:4])}, {v[4]}}},")
    out.append("    },")
    out.append("    zones = {")
    for k, v in zones.items():
        extra = ", true" if len(v) > 8 else ""
        out.append(f"        [{k}] = {{{', '.join(num(x) for x in v[:4])}, {v[4]}, {v[5]}, {lua_str(v[6])}, {v[7]}{extra}}},")
    out.append("    },")
    out.append("    areas = {")
    for k, (m, n) in areas.items():
        out.append(f"        [{k}] = {{{m}, {lua_str(n)}}},")
    out.append("    },")
    out.append("}")
    return "\n".join(out)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("stock_dbc")
    p.add_argument("out_dir")
    p.add_argument("--realm", action="append", required=True, metavar="NAME=DBC_DIR")
    a = p.parse_args()
    parts = ["-- Generated by WHE's tools/questie/questie_whe.py from the realms' DBCs: rerun it, don't edit.",
             "QuestieWHE_Data = {}"]
    for spec in a.realm:
        name, _, dbc_dir = spec.partition("=")
        moved, zones, areas = realm_data(a.stock_dbc, dbc_dir)
        print(f"{name}: {len(moved)} moved maps, {len(zones)} new maps, {len(areas)} new areas")
        parts.append(emit(name, moved, zones, areas))
    os.makedirs(a.out_dir, exist_ok=True)
    with open(os.path.join(a.out_dir, "Data.lua"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts) + "\n")
    with open(os.path.join(a.out_dir, "Questie-X-WHE.toc"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(TOC)
    shutil.copyfile(os.path.join(os.path.dirname(os.path.abspath(__file__)), "Plugin.lua"),
                    os.path.join(a.out_dir, "Plugin.lua"))


if __name__ == "__main__":
    main()
