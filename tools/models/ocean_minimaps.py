#!/usr/bin/env python3
"""Minimap entries for ocean filler tiles: md5translate rows so copied tiles show sea, not the last tile drawn.

  python ocean_minimaps.py PATCH_DIR TRS OUT.sql [--maps Azeroth,Kalimdor]

PATCH_DIR is a patch folder whose World/Maps/<map>/ holds a map's full tile grid, where the tiles the map didn't
have are byte-copies of a few of its open-sea tiles (the squished client's ocean patch, over Open Azeroth's
continents). TRS is the md5translate.trs those originals' minimap images are named in (Open Azeroth's, from its
patch-4.MPQ). Each tile TRS has no entry for gets one pointing at the image of the original it copies.

Without an entry the client keeps whatever texture that minimap slot last held (SetupTextureHandles only logs
MINIMAPCHUNKNOTFOUND), so the minimap over the filler tiles shows pieces of the coast passed before.

Writes F-010's md5translate rows in the DELETE + INSERT form build-dbc.sh applies; they only reach the client when
the server's build-dbc.conf sets ORIGINAL_TRS (the stock md5translate.trs the table starts from)."""
import argparse, collections, hashlib, os, re, sys

BS = "\\"


def read_trs(path):
    out = {}
    for line in open(path, encoding="latin1").read().replace("\r", "").split("\n"):
        if "\t" in line:
            src, dst = line.split("\t", 1)
            out[src.lower()] = dst
    return out


def q(s):
    return "'" + s.replace(BS, BS + BS).replace("'", "''") + "'"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("patch_dir")
    p.add_argument("trs")
    p.add_argument("out")
    p.add_argument("--maps", default="Azeroth,Kalimdor")
    a = p.parse_args()
    trs = read_trs(a.trs)
    rows = []
    for name in a.maps.split(","):
        folder = next((os.path.join(dp, d) for dp, ds, _ in os.walk(a.patch_dir) for d in ds
                       if d.lower() == name.lower() and os.path.basename(dp).lower() == "maps"), None)
        if not folder:
            sys.exit(f"no World/Maps/{name} in {a.patch_dir}")
        by_content = collections.defaultdict(list)
        for f in os.listdir(folder):
            m = re.fullmatch(r".+_(\d+)_(\d+)\.adt", f, re.I)
            if m:
                digest = hashlib.md5(open(os.path.join(folder, f), "rb").read()).hexdigest()
                by_content[digest].append((int(m.group(1)), int(m.group(2))))
        key = lambda x, y: f"{name}{BS}map{x:02}_{y:02}.blp"  # noqa: E731
        added = 0
        for tiles in by_content.values():
            source = next((trs[key(x, y).lower()] for x, y in tiles if key(x, y).lower() in trs), None)
            for x, y in tiles:
                if key(x, y).lower() in trs:
                    continue
                if source is None:
                    print(f"{name} {x}_{y}: copies no tile with a minimap image, skipped")
                    continue
                rows.append((key(x, y), source, name))
                added += 1
        print(f"{name}: {added} filler tiles")
    rows.sort()
    out = ["-- Generated by tools/models/ocean_minimaps.py: minimap images for the ocean filler tiles around Open",
           "-- Azeroth's continents (each points at the sea image of the tile it copies). Needs ORIGINAL_TRS on the",
           "-- build server, see the script.", ""]
    for i in range(0, len(rows), 500):
        part = rows[i:i + 500]
        out.append("DELETE FROM `md5translate` WHERE `src` IN (" + ", ".join(q(r[0]) for r in part) + ");")
        out.append("INSERT INTO `md5translate` (`src`, `dst`, `dir`) VALUES\n"
                   + ",\n".join(f"({q(s)}, {q(d)}, {q(m)})" for s, d, m in part) + ";")
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"{len(rows)} rows -> {a.out}")


if __name__ == "__main__":
    main()
